const byKey = new Map(SUBJECTS.map((s) => [s.name.replace(/\s+/g, ''), s]));
const AREAS = new Set(['국어', '수학', '영어', '사회', '과학', '정보', '한문', '제2외국어', '예술', '체육', '교양', '역사', '도덕', '지리', '윤리', '일반사회']);

/** 권장과목 조각 → { name, subject|null, isArea } */
export function resolve(token) {
  const t = String(token || '').trim();
  const key = t.replace(/\s+/g, '').replace(/I$/, 'Ⅰ');
  const name = ALIAS[key] || t;
  const subject = byKey.get(String(name).replace(/\s+/g, '')) || null;
  const isArea = !subject && (AREAS.has(key) || /교과|영역|관련 과목/.test(t));
  return { token: t, name: subject ? subject.name : t, subject, isArea };
}


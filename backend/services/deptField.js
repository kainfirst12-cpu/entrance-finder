// 모집단위가 계열을 가리지 않는 것들 — 미분류로 남긴다
const CROSS = /자유전공|자율전공|무전공|계열구분없음|학부대학|공통|융합인재|열린전공/;

/** 학과명 → '인문' | '자연' | '예체능' | '' (미분류) */
export function fieldOf(dept) {
  const d = String(dept || '').normalize('NFC');
  if (!d) return '';
  // 모집단위 이름이 계열을 직접 밝힌 경우가 먼저다 — '자유전공학부(자연계열)'은 자유전공이 아니라 이과다
  if (/\(자연|자연\)|자연계열|이과/.test(d)) return '자연';
  if (/\(인문|인문\)|인문계열|인문사회|문과/.test(d)) return '인문';
  if (CROSS.test(d)) return '';
  for (const [field, re] of RULES) if (re.test(d)) return field;
  return '';
}

